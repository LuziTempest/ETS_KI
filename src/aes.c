/* Mengalikan dua byte dalam GF(2^8) untuk operasi AES seperti MixColumns. */
static uint8_t gf_multiply(uint8_t a, uint8_t b)
{
    uint8_t result = 0;
    while (b != 0) {
        if (b & 1) result ^= a;
        a = (uint8_t)((a << 1) ^ ((a & 0x80) ? 0x1b : 0));
        b >>= 1;
    }
    return result;
}

/* Memperluas kunci 16 byte menjadi 11 kunci ronde AES-128. */
static void key_expansion(const uint8_t key[16], uint8_t expanded[176])
{
    unsigned int used = 16;
    uint8_t rcon = 1, temp[4];
    memcpy(expanded, key, 16);
    while (used < 176) {
        memcpy(temp, expanded + used - 4, 4);
        if (used % 16 == 0) {
            uint8_t first = temp[0];
            temp[0] = (uint8_t)(sbox[temp[1]] ^ rcon);
            temp[1] = sbox[temp[2]];
            temp[2] = sbox[temp[3]];
            temp[3] = sbox[first];
            rcon = gf_multiply(rcon, 2);
        }
        for (int i = 0; i < 4; ++i, ++used)
            expanded[used] = (uint8_t)(expanded[used - 16] ^ temp[i]);
    }
}

/* Menggabungkan state dengan kunci ronde melalui XOR byte demi byte. */
static void add_round_key(uint8_t state[16], const uint8_t key[16])
{
    for (int i = 0; i < 16; ++i) state[i] ^= key[i];
}

/* Mengganti setiap byte state dengan nilai pada S-box untuk enkripsi. */
static void sub_bytes(uint8_t state[16])
{
    for (int i = 0; i < 16; ++i) state[i] = sbox[state[i]];
}

/* Membalik substitusi setiap byte state memakai invers S-box untuk dekripsi. */
static void inv_sub_bytes(uint8_t state[16])
{
    for (int i = 0; i < 16; ++i) state[i] = inv_sbox[state[i]];
}

/* Menggeser tiap baris state ke kiri sesuai nomor baris saat enkripsi. */
static void shift_rows(uint8_t state[16])
{
    uint8_t copy[16];
    memcpy(copy, state, 16);
    for (int row = 0; row < 4; ++row)
        for (int col = 0; col < 4; ++col)
            state[4 * col + row] = copy[4 * ((col + row) % 4) + row];
}

/* Menggeser tiap baris state ke kanan untuk membalik ShiftRows saat dekripsi. */
static void inv_shift_rows(uint8_t state[16])
{
    uint8_t copy[16];
    memcpy(copy, state, 16);
    for (int row = 0; row < 4; ++row)
        for (int col = 0; col < 4; ++col)
            state[4 * col + row] = copy[4 * ((col - row + 4) % 4) + row];
}

/* Mencampur empat byte pada tiap kolom state dengan perkalian GF(2^8). */
static void mix_columns(uint8_t state[16])
{
    for (int col = 0; col < 4; ++col) {
        uint8_t *s = state + 4 * col;
        uint8_t a = s[0], b = s[1], c = s[2], d = s[3];
        s[0] = gf_multiply(a,2) ^ gf_multiply(b,3) ^ c ^ d;
        s[1] = a ^ gf_multiply(b,2) ^ gf_multiply(c,3) ^ d;
        s[2] = a ^ b ^ gf_multiply(c,2) ^ gf_multiply(d,3);
        s[3] = gf_multiply(a,3) ^ b ^ c ^ gf_multiply(d,2);
    }
}

/* Membalik pencampuran byte pada tiap kolom state saat dekripsi. */
static void inv_mix_columns(uint8_t state[16])
{
    for (int col = 0; col < 4; ++col) {
        uint8_t *s = state + 4 * col;
        uint8_t a = s[0], b = s[1], c = s[2], d = s[3];
        s[0] = gf_multiply(a,14) ^ gf_multiply(b,11) ^ gf_multiply(c,13) ^ gf_multiply(d,9);
        s[1] = gf_multiply(a,9) ^ gf_multiply(b,14) ^ gf_multiply(c,11) ^ gf_multiply(d,13);
        s[2] = gf_multiply(a,13) ^ gf_multiply(b,9) ^ gf_multiply(c,14) ^ gf_multiply(d,11);
        s[3] = gf_multiply(a,11) ^ gf_multiply(b,13) ^ gf_multiply(c,9) ^ gf_multiply(d,14);
    }
}

/* Menyiapkan konteks AES-128 dengan menghitung semua kunci ronde. */
void aes128_init(AES128Context *ctx, const uint8_t key[16])
{
    key_expansion(key, ctx->round_keys);
}

/* Mengenkripsi satu blok 16 byte melalui sepuluh ronde AES-128. */
void aes128_encrypt_block(const AES128Context *ctx,
                          const uint8_t input[16], uint8_t output[16])
{
    uint8_t state[16];
    memcpy(state, input, 16);
    add_round_key(state, ctx->round_keys);
    for (int round = 1; round <= 10; ++round) {
        sub_bytes(state);
        shift_rows(state);
        if (round != 10) mix_columns(state);
        add_round_key(state, ctx->round_keys + 16 * round);
    }
    memcpy(output, state, 16);
}

/* Mendekripsi satu blok 16 byte dengan operasi ronde AES-128 terbalik. */
void aes128_decrypt_block(const AES128Context *ctx,
                          const uint8_t input[16], uint8_t output[16])
{
    uint8_t state[16];
    memcpy(state, input, 16);
    add_round_key(state, ctx->round_keys + 160);
    for (int round = 9; round >= 0; --round) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, ctx->round_keys + 16 * round);
        if (round != 0) inv_mix_columns(state);
    }
    memcpy(output, state, 16);
}
